// Bundles src/lib/ogSummary.ts (and the site's model it uses) into one Node script for the
// checker on the server: data_bundles/og_summary.mjs in the tech-news repo. The server's
// og_image.py runs it as `node og_summary.mjs < document.json` and draws what it prints.
// Re-run this and copy the output to the server whenever src/lib/dataBundles.ts changes.
//
// Run: node scripts/build-og-summary.mjs <out-file>
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = process.argv[2];
if (!out) {
  console.error("usage: node scripts/build-og-summary.mjs <out-file>");
  process.exit(1);
}
const srcHash = createHash("sha256").update(readFileSync(new URL("../src/lib/dataBundles.ts", import.meta.url))).update(readFileSync(new URL("../src/lib/ogSummary.ts", import.meta.url))).update(readFileSync(new URL("../src/lib/bundleSheet.ts", import.meta.url))).digest("hex").slice(0, 12);
await build({
  stdin: {
    contents: `import { ogSummary } from "./src/lib/ogSummary.ts";
let raw = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (c) => { raw += c; });
process.stdin.on("end", () => { process.stdout.write(JSON.stringify(ogSummary(JSON.parse(raw)))); });`,
    resolveDir: fileURLToPath(new URL("..", import.meta.url)),
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: out,
  banner: { js: `// GENERATED by techtrendi scripts/build-og-summary.mjs from src/lib/ogSummary.ts + src/lib/bundleSheet.ts + src/lib/dataBundles.ts (sources sha ${srcHash}). Do not edit.` },
  logLevel: "warning",
});
console.log(`wrote ${out} (sources sha ${srcHash})`);
